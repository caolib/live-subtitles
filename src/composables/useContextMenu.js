/**
 * 创建并显示原生上下文菜单
 * 
 * @param {Object} context - 包含所有需要的状态和方法的上下文对象
 * @param {Object} context.settingsStore - 设置 Store
 * @param {Object} context.windowControl - 窗口控制相关 (isLocked, toggleLock, etc.)
 * @param {Object} context.subtitleControl - 字幕控制相关 (isRunning, toggleRecognition, etc.)
 * @param {Object} context.styleManager - 样式管理 (openStyleEditor)
 * @param {Object} context.appConfig - 应用配置 (openSettings)
 */
export function useContextMenu({ settingsStore, windowControl, subtitleControl, styleManager, appConfig }) {

    async function showContextMenu(event) {
        // 阻止默认的浏览器右键菜单
        if (event) {
            event.preventDefault();
        }

        try {
            const menu = await Menu.new({
                items: [
                    // 状态控制
                    await IconMenuItem.new({
                        text: subtitleControl.isRunning.value ? '⏸ 暂停识别' : '▶ 开始识别',
                        action: () => subtitleControl.toggleRecognition()
                    }),

                    await PredefinedMenuItem.new({ item: 'Separator' }),

                    // 窗口控制
                    await CheckMenuItem.new({
                        text: '🔒 锁定位置与大小',
                        checked: windowControl.isLocked.value,
                        action: () => windowControl.toggleLock()
                    }),
                    await CheckMenuItem.new({
                        text: '📌 始终置顶',
                        checked: await getCurrentWindow().isAlwaysOnTop(),
                        action: async () => {
                            const win = getCurrentWindow();
                            const isTop = await win.isAlwaysOnTop();
                            await win.setAlwaysOnTop(!isTop);
                        }
                    }),

                    await PredefinedMenuItem.new({ item: 'Separator' }),

                    // 功能选项
                    await CheckMenuItem.new({
                        text: '📜 显示历史记录',
                        checked: settingsStore.showHistory,
                        action: () => subtitleControl.toggleHistory()
                    }),
                    await CheckMenuItem.new({
                        text: '🔤 小写转换',
                        checked: settingsStore.lowercaseSubtitle,
                        action: () => subtitleControl.toggleCase()
                    }),
                    await IconMenuItem.new({
                        text: '📋 复制全部文本',
                        action: () => subtitleControl.copyAllText()
                    }),
                    await IconMenuItem.new({
                        text: '🗑️ 清空字幕',
                        action: () => subtitleControl.clearSubtitles()
                    }),

                    await PredefinedMenuItem.new({ item: 'Separator' }),

                    // 设置与工具
                    await IconMenuItem.new({
                        text: '🎨 样式编辑器',
                        action: () => styleManager.openStyleEditor()
                    }),
                    await IconMenuItem.new({
                        text: '⚙️ 设置',
                        action: () => appConfig.openSettings()
                    }),

                    await PredefinedMenuItem.new({ item: 'Separator' }),

                    // 应用控制
                    await IconMenuItem.new({
                        text: '❌ 退出',
                        action: async () => {
                            await getCurrentWindow().close();
                        }
                    })
                ]
            });

            // 在鼠标位置弹出菜单
            await menu.popup();

        } catch (error) {
            console.error("Fail to open context menu:", error);
        }
    }

    return {
        showContextMenu
    };
}
